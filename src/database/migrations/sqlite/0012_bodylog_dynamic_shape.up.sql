    FROM PON_USER_BODYLOG_OLD o
    JOIN PON_USER_BODY_METRIC m ON m.USER_ID = o.USER_ID AND m.NAME = 'Heart Rate'
    WHERE o.HEART_RATE_BPM IS NOT NULL;

INSERT INTO PON_USER_BODYLOG_METRIC (BODYLOG_ID, BODY_METRIC_ID, VALUE)
    SELECT o.ID, m.ID, o.STEPS_COUNT
    FROM PON_USER_BODYLOG_OLD o
    JOIN PON_USER_BODY_METRIC m ON m.USER_ID = o.USER_ID AND m.NAME = 'Steps'
