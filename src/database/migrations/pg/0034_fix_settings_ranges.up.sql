-- Settings numbers were saved without range checks; the server now rejects
-- values outside these ranges (constants/limits.go). Reset any
-- stored value outside its range to the default for new users.
UPDATE PON.USER SET TARGET_BLOOD_SUGAR = 5.6
WHERE TARGET_BLOOD_SUGAR <= 0 OR TARGET_BLOOD_SUGAR > 1000;

UPDATE PON.USER SET INSULIN_SENSITIVITY_FACTOR = 3
WHERE INSULIN_SENSITIVITY_FACTOR <= 0 OR INSULIN_SENSITIVITY_FACTOR > 1000;

UPDATE PON.USER SET EVENT_LOG_TRAILING_ROWS = 3
WHERE EVENT_LOG_TRAILING_ROWS < 0 OR EVENT_LOG_TRAILING_ROWS > 20;

UPDATE PON.USER SET EVENT_HISTORY_FETCH_LIMIT = 50
WHERE EVENT_HISTORY_FETCH_LIMIT < 1 OR EVENT_HISTORY_FETCH_LIMIT > 1000;

UPDATE PON.USER SET TIMESPAN_HISTORY_FETCH_LIMIT = 50
WHERE TIMESPAN_HISTORY_FETCH_LIMIT < 1 OR TIMESPAN_HISTORY_FETCH_LIMIT > 1000;

UPDATE PON.USER SET DAY_TIME_OFFSET_SECONDS = 0
WHERE DAY_TIME_OFFSET_SECONDS < 0 OR DAY_TIME_OFFSET_SECONDS > 86399;
